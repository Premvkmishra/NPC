export function PixelIcon({ name, size = 20, className }: { name: string; size?: number; className?: string }) {
  const rows = ICONS[name] ?? ICONS["star"]!;
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden className={className} fill="currentColor">
      {rows.flatMap((r, y) => [...r].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null)))}
    </svg>
  );
}

